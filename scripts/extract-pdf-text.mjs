/**
 * One-time (re-runnable) extraction of application-note PDF text.
 *
 *   node scripts/extract-pdf-text.mjs
 *
 * Reads every unique PDF referenced in src/data/applicationNotes.js, extracts
 * text, cleans + chunks it, and writes src/data/pdfKnowledge.js. The chat then
 * retrieves the most relevant chunks per question (mini-RAG over the PDFs).
 */

import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { dirname, resolve } from 'node:path'
import { createRequire } from 'node:module'

const require = createRequire(import.meta.url)
const { PDFParse } = require('pdf-parse')

const __dirname = dirname(fileURLToPath(import.meta.url))
const ROOT = resolve(__dirname, '..')

const { getApplicationNotes } = await import(
  resolve(ROOT, 'src/data/applicationNotes.js')
)

const CHUNK_SIZE = 900
const CHUNK_OVERLAP = 150

function cleanText(raw) {
  return String(raw || '')
    .replace(/\r/g, '\n')
    // drop obvious boilerplate lines
    .split('\n')
    .map((l) => l.trim())
    .filter((l) => l && !/^\d+$/.test(l) && !/^page \d+/i.test(l))
    .join(' ')
    .replace(/\s+/g, ' ')
    .replace(/-\s+/g, '') // de-hyphenate line breaks
    .trim()
}

function chunkText(text) {
  const chunks = []
  let i = 0
  while (i < text.length) {
    let end = Math.min(i + CHUNK_SIZE, text.length)
    // prefer to break on a sentence/space boundary
    if (end < text.length) {
      const slice = text.slice(i, end)
      const lastStop = Math.max(slice.lastIndexOf('. '), slice.lastIndexOf(' '))
      if (lastStop > CHUNK_SIZE * 0.5) end = i + lastStop + 1
    }
    const piece = text.slice(i, end).trim()
    if (piece.length > 40) chunks.push(piece)
    if (end >= text.length) break
    i = end - CHUNK_OVERLAP
  }
  return chunks
}

async function main() {
  const notes = getApplicationNotes()
  const out = []
  let totalChunks = 0

  for (const note of notes) {
    // note.pdf is like "/PDF/File.pdf" served from public/
    const filePath = resolve(ROOT, 'public', `.${note.pdf}`)
    let parser
    try {
      const buf = await readFile(filePath)
      parser = new PDFParse({ data: new Uint8Array(buf) })
      const parsed = await parser.getText()
      const text = cleanText(parsed.text)
      const chunks = chunkText(text)
      totalChunks += chunks.length
      out.push({
        pdf: note.pdf,
        title: note.label,
        industries: note.industries,
        pages: parsed.total ?? parsed.pages?.length ?? 0,
        chars: text.length,
        chunks,
      })
      console.log(
        `✓ ${note.label} — ${text.length} chars, ${chunks.length} chunks`,
      )
    } catch (err) {
      console.warn(`✗ ${note.label} (${note.pdf}): ${err.message}`)
      out.push({
        pdf: note.pdf,
        title: note.label,
        industries: note.industries,
        pages: 0,
        chars: 0,
        chunks: [],
      })
    } finally {
      try {
        await parser?.destroy()
      } catch {
        /* ignore */
      }
    }
  }

  const header = `/**
 * AUTO-GENERATED by scripts/extract-pdf-text.mjs — do not edit by hand.
 * Extracted text of the application-note PDFs (public/PDF), chunked for
 * retrieval by the support chat. Re-run the script after changing PDFs.
 */
`
  const body = `export const PDF_KNOWLEDGE = ${JSON.stringify(out, null, 2)}\n`
  await writeFile(resolve(ROOT, 'src/data/pdfKnowledge.js'), header + body, 'utf8')

  console.log(
    `\nWrote src/data/pdfKnowledge.js — ${out.length} notes, ${totalChunks} chunks.`,
  )
}

main().catch((err) => {
  console.error(err)
  process.exit(1)
})
